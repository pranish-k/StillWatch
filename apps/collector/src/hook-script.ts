import { stillwatchPaths } from '@stillwatch/schema';

export type HookScriptOptions = {
  stillwatchHome: string;
  /** Node binary that starts the collector when it is not running. */
  nodePath: string;
  /** CLI entry script that accepts `start --quiet`. */
  cliPath: string;
};

/** Quotes a string for POSIX sh: wraps it in single quotes, writing each ' as '\''. */
function shellQuote(value: string): string {
  return `'${value.replaceAll("'", "'\\''")}'`;
}

/**
 * POSIX sh source of the capture hook (ADR-016). Invoked by Claude Code in
 * exec form as `/bin/sh <hook.sh> <agent> <EventName> [--ensure-collector]`
 * with the payload on stdin. It writes stdin to
 * `spool/tmp/<agent>.<Event>.<suffix>` (mode 0600, created exclusively with
 * noclobber and the pid plus $RANDOM, or with mktemp when the shell has no
 * $RANDOM), renames it into
 * `spool/new/`, optionally starts the collector in the background
 * (`STILLWATCH_HOME=<home> <node> <cli> start --quiet`, stdio to /dev/null),
 * and always exits 0 without writing to stdout. Agent and event arguments are
 * validated against [a-z0-9-] and [A-Za-z0-9]. Embedded paths are
 * single-quoted with proper escaping.
 */
export function renderHookScript(options: HookScriptOptions): string {
  const paths = stillwatchPaths(options.stillwatchHome);
  const home = shellQuote(options.stillwatchHome);
  return `#!/bin/sh
# Stillwatch capture hook. Generated by \`stillwatch install\`; do not edit.
# Copies the hook payload on stdin into the spool and exits 0. It never
# writes to stdout (stdout of some hooks becomes agent context) and never
# exits non-zero (exit 2 would block the agent).
exec >/dev/null 2>&1
umask 077
LC_ALL=C
export LC_ALL

tmpdir=${shellQuote(paths.spoolTmp)}
newdir=${shellQuote(paths.spoolNew)}
pidfile=${shellQuote(paths.pidFile)}

agent=\${1:-}
event=\${2:-}
case $agent in
  [a-z]*) case $agent in *[!a-z0-9-]*) agent=unknown ;; esac ;;
  *) agent=unknown ;;
esac
[ \${#agent} -le 32 ] || agent=unknown
case $event in
  [A-Za-z]*) case $event in *[!A-Za-z0-9]*) event=Unknown ;; esac ;;
  *) event=Unknown ;;
esac
[ \${#event} -le 40 ] || event=Unknown

# Create the temp file in the shell when it has $RANDOM (saves a mktemp
# process on every event); noclobber makes the create exclusive.
tmp=
if [ -n "\${RANDOM:-}" ]; then
  set -C
  n=0
  while [ "$n" -lt 4 ]; do
    try="$tmpdir/$agent.$event.p$$r\${RANDOM}r\${RANDOM}"
    if : >"$try"; then
      tmp=$try
      break
    fi
    [ -d "$tmpdir" ] || mkdir -p "$tmpdir" "$newdir"
    n=$((n + 1))
  done
  set +C
fi
if [ -z "$tmp" ]; then
  tmp=$(mktemp "$tmpdir/$agent.$event.XXXXXXXXXX") || {
    mkdir -p "$tmpdir" "$newdir"
    tmp=$(mktemp "$tmpdir/$agent.$event.XXXXXXXXXX")
  } || tmp=
fi
if [ -n "$tmp" ]; then
  if cat >"$tmp"; then
    mv -f "$tmp" "$newdir/" || { mkdir -p "$newdir" && mv -f "$tmp" "$newdir/"; } || rm -f "$tmp"
  else
    rm -f "$tmp"
  fi
fi

if [ "\${3:-}" = "--ensure-collector" ]; then
  pid=
  if [ -r "$pidfile" ]; then
    read -r pid <"$pidfile" || :
  fi
  case $pid in ''|*[!0-9]*) pid= ;; esac
  if [ -z "$pid" ] || ! kill -0 "$pid"; then
    STILLWATCH_HOME=${home} ${shellQuote(options.nodePath)} ${shellQuote(options.cliPath)} start --quiet </dev/null >/dev/null 2>&1 &
  fi
fi
exit 0
`;
}
